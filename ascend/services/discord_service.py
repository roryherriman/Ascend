"""Discord weekly summary service.

Builds a text summary of the raid week and posts it to a Discord webhook.
Uses only data already in the local SQLite database — no live API calls.
"""
from __future__ import annotations

from datetime import datetime, timedelta, timezone

import requests

from ascend.data.database import Database
from ascend.data.repositories import ReportRepository
from ascend.metadata import APP_NAME, APP_VERSION


def _recent_week_reports(db: Database, days: int = 7) -> list:
    repo = ReportRepository(db)
    all_reports = repo.list_all()
    cutoff = (datetime.now(timezone.utc) - timedelta(days=days)).timestamp() * 1000
    return [r for r in all_reports if (r.start_time or 0) >= cutoff]


def build_weekly_summary(db: Database, days: int = 7) -> str:
    """Build a plain-text Discord summary of the last `days` days."""
    repo = ReportRepository(db)
    reports = _recent_week_reports(db, days)

    if not reports:
        return (
            f"**{APP_NAME} Weekly Summary**\n"
            f"No raid nights logged in the last {days} days."
        )

    total_pulls = 0
    total_kills = 0
    encounter_names: set[str] = set()

    for report in reports:
        if report.id is None:
            continue
        fights = repo.fights_for_report(report.id)
        total_pulls += len(fights)
        total_kills += sum(1 for f in fights if f.kill)
        for f in fights:
            if f.name:
                encounter_names.add(f.name)

    kill_rate = round(100 * total_kills / total_pulls) if total_pulls else 0
    nights = len(reports)
    bosses = len(encounter_names)

    lines = [
        f"**{APP_NAME} Weekly Summary** (last {days} days)",
        "",
        f"Raid nights: **{nights}**",
        f"Total pulls: **{total_pulls}**",
        f"Total kills: **{total_kills}** ({kill_rate}% kill rate)",
        f"Encounters touched: **{bosses}**",
    ]

    if encounter_names:
        sorted_enc = sorted(encounter_names)
        lines.append("")
        lines.append("**Encounters:**")
        for enc in sorted_enc:
            lines.append(f"  • {enc}")

    lines += [
        "",
        f"*Generated by {APP_NAME} v{APP_VERSION}*",
    ]

    return "\n".join(lines)


def post_weekly_summary(
    db: Database,
    webhook_url: str,
    days: int = 7,
    timeout: float = 10.0,
) -> tuple[bool, str]:
    """Post the weekly summary to `webhook_url`. Returns (ok, message)."""
    if not webhook_url:
        return False, "No Discord webhook URL configured."

    summary = build_weekly_summary(db, days)
    try:
        resp = requests.post(
            webhook_url,
            json={"content": summary, "username": APP_NAME},
            timeout=timeout,
        )
    except requests.exceptions.RequestException as exc:
        return False, str(exc)

    if resp.status_code in (200, 204):
        return True, "Summary posted to Discord."
    return False, f"Discord returned HTTP {resp.status_code}."
